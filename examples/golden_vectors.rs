//! Emit the cross-language conformance fixture for `th3seus-web`.
//!
//! The configurator computes thrust-to-weight, flight time and peak current in
//! TypeScript, because it must show them before any daemon is connected. That
//! is a second implementation of this crate's model, and it has silently
//! drifted twice — most recently for the three months between the 2026-05-30
//! recalibration and 2026-08-29, during which the configurator advertised a
//! thrust-to-weight ratio roughly three times what the daemon would simulate.
//!
//! A comment asking the next author to keep two files in sync failed both
//! times. These vectors are the contract instead: the TypeScript suite asserts
//! against them, so a change here that moves the numbers fails the web build.
//!
//!   cargo run --example golden_vectors > \
//!     ../th3seus-web/packages/calculators/src/engines/__fixtures__/physics-golden.json
