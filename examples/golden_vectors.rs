fn spec_of(c: &Case) -> BuildSpec {
    let mut s = BuildSpec::default();
    s.frame.weight_g = c.frame_g;
    s.motors.kv = c.kv;
    s.motors.weight_g = c.motor_g;
    s.propellers.diameter_in = c.diameter_in;
    s.propellers.pitch_in = c.pitch_in;
    s.propellers.blade_count = c.blades;
    s.propellers.weight_g = Some(c.prop_g);
    s.escs.weight_g = Some(c.esc_total_g);
    s.escs.burst_amps = Some(c.esc_burst_a);
    s.battery.cell_count = c.cells;
    s.battery.capacity_mah = c.capacity_mah;
    s.battery.c_rating = c.c_rating;
    s.battery.weight_g = c.battery_g;
    s.flight_controller.weight_g = c.fc_g;
    s.gps = c.gps_g.map(|g| GpsSpec {
        chipset: GpsChipset::UbloxM10,
        update_rate_hz: 10.0,
        has_compass: true,
        weight_g: g,
    });
    s
}

fn main() {
    println!("{{");
    println!(
        "  \"_comment\": \"GENERATED by `cargo run --example golden_vectors` in hitl-physics. Do not edit by hand. Regenerate when the Rust model changes; a diff here is the intended signal that the TypeScript port must follow.\","
    );
    println!("  \"cases\": [");
    for (i, c) in CASES.iter().enumerate() {
        let spec = spec_of(c);
        let p = spec.to_physics_config();
        let omega = p.max_motor_speed_from_voltage();
        let comma = if i + 1 == CASES.len() { "" } else { "," };
        println!("    {{");
        println!("      \"name\": \"{}\",", c.name);
        println!("      \"input\": {{");
        println!("        \"kv\": {}, \"motorWeightG\": {},", c.kv, c.motor_g);
        println!(
            "        \"propDiameterIn\": {}, \"propPitchIn\": {}, \"bladeCount\": {}, \"propWeightG\": {},",
            c.diameter_in, c.pitch_in, c.blades, c.prop_g
        );
        println!(
            "        \"cellCount\": {}, \"capacityMah\": {}, \"cRating\": {}, \"batteryWeightG\": {},",
            c.cells, c.capacity_mah, c.c_rating, c.battery_g
        );
        println!(
            "        \"frameWeightG\": {}, \"escTotalWeightG\": {}, \"escBurstAmps\": {}, \"fcWeightG\": {}, \"gpsWeightG\": {}",
            c.frame_g,
            c.esc_total_g,
            c.esc_burst_a,
            c.fc_g,
            c.gps_g.map(|g| g.to_string()).unwrap_or("null".into())
        );
        println!("      }},");
        println!("      \"expected\": {{");
        println!("        \"kt\": {:.12e},", p.kt);
        println!("        \"kq\": {:.12e},", p.kq);
        println!("        \"massKg\": {:.9},", p.mass_kg);
        println!("        \"batteryVoltage\": {:.9},", p.battery_voltage);
        println!(
            "        \"motorResistanceOhm\": {:.9},",
            p.motor_resistance_ohm
        );
        println!(
            "        \"maxCurrentPerMotorA\": {:.9},",
            p.max_current_per_motor_a
        );
        println!("        \"maxOmegaRadS\": {:.9},", omega);
        println!(
            "        \"maxThrustPerMotorG\": {:.9},",
            p.max_thrust_per_motor_n() / 9.80665 * 1000.0
        );
        println!(
            "        \"thrustToWeightRatio\": {:.9},",
            4.0 * p.max_thrust_per_motor_n() / (p.mass_kg * 9.80665)
        );
        println!(
            "        \"hoverThrottlePercent\": {:.9},",
            p.hover_throttle_percent()
        );
        println!("        \"isCurrentLimited\": {}", p.is_current_limited());
        println!("      }}");
        println!("    }}{comma}");
    }
    println!("  ]");
    println!("}}");
}
